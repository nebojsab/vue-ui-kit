#!/usr/bin/env node
// Generates src/index.d.ts from the components' runtime props (defineProps({...})),
// their JSDoc comments and defineEmits([...]). Run: npm run build:types
//
// A comment that starts with a union of string literals — /** 'sm' | 'md' */ — becomes that
// union (plus `string & {}`, so other values still type-check but editors autocomplete these).
import { readFileSync, writeFileSync } from 'node:fs'
import { parse, compileScript } from 'vue/compiler-sfc'

const index = readFileSync('src/index.js', 'utf8')
const comps = [...index.matchAll(/export \{ default as (\w+) \} from '\.\/(.+?\.vue)'/g)].map((m) => ({ name: m[1], file: `src/${m[2]}` }))

const CTOR = {
  String: 'string', Number: 'number', Boolean: 'boolean', Array: 'any[]',
  Object: 'Record<string, any>', Function: '((...args: any[]) => any)', Date: 'Date',
}
const ctorType = (node) => {
  if (!node) return 'any'
  if (node.type === 'Identifier') return CTOR[node.name] ?? 'any'
  if (node.type === 'ArrayExpression') return [...new Set(node.elements.map(ctorType))].join(' | ')
  return 'any'
}
const docOf = (prop) => (prop.leadingComments ?? []).filter((c) => c.type === 'CommentBlock').map((c) => c.value).pop()
const cleanDoc = (raw) => raw?.split('\n').map((l) => l.replace(/^\s*\*\s?/, '')).join('\n').trim()
const literalUnion = (doc) => {
  const m = doc?.match(/^((?:'[^']*'\s*\|\s*)+'[^']*')/)
  return m ? m[1].split('|').map((s) => s.trim()) : null
}

function propsOf(file, src, name) {
  const { descriptor } = parse(src, { filename: file })
  if (!descriptor.scriptSetup) return { props: [], emits: [] }
  const sc = compileScript(descriptor, { id: name })
  const body = sc.scriptSetupAst ?? []
  let propsObj = null
  let emits = []
  const visit = (n) => {
    if (!n || typeof n !== 'object') return
    if (n.type === 'CallExpression' && n.callee?.name === 'defineProps' && n.arguments[0]?.type === 'ObjectExpression') propsObj = n.arguments[0]
    if (n.type === 'CallExpression' && n.callee?.name === 'defineEmits' && n.arguments[0]?.type === 'ArrayExpression') emits = n.arguments[0].elements.map((e) => e.value)
    for (const k in n) if (k !== 'leadingComments' && k !== 'trailingComments' && k !== 'loc') {
      const v = n[k]
      Array.isArray(v) ? v.forEach(visit) : v && typeof v.type === 'string' && visit(v)
    }
  }
  body.forEach(visit)
  const props = (propsObj?.properties ?? []).map((p) => {
    const key = p.key.name ?? p.key.value
    let type = 'any'
    let required = false
    if (p.value.type === 'Identifier' || p.value.type === 'ArrayExpression') type = ctorType(p.value)
    else if (p.value.type === 'ObjectExpression') {
      const get = (k) => p.value.properties.find((q) => (q.key?.name ?? q.key?.value) === k)
      type = ctorType(get('type')?.value)
      required = get('required')?.value?.value === true
    }
    const doc = cleanDoc(docOf(p))
    const union = type.includes('string') ? literalUnion(doc) : null
    if (union) type = `${union.join(' | ')}${type === 'string' ? ' | (string & {})' : ` | ${type.replace('string', '(string & {})')}`}`
    return { key, type, required, doc }
  })
  return { props, emits }
}

const quote = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`)
// 'update:modelValue' → 'onUpdate:modelValue' · 'row-click' → 'onRowClick'
const handler = (e) => e.startsWith('update:') ? `onUpdate:${e.slice(7)}` : `on${e.split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join('')}`
const lines = [
  '// Generated by scripts/gen-types.mjs — do not edit by hand.',
  "import type { DefineComponent, Ref, ComputedRef } from 'vue'",
  '',
]
for (const { name, file } of comps) {
  const { props, emits } = propsOf(file, readFileSync(file, 'utf8'), name)
  lines.push(`export interface ${name}Props {`)
  for (const p of props) {
    if (p.doc) lines.push(`  /** ${p.doc.replace(/\*\//g, '* /').replace(/\n/g, '\n   * ')} */`)
    lines.push(`  ${quote(p.key)}${p.required ? '' : '?'}: ${p.type}`)
  }
  for (const e of emits) lines.push(`  ${quote(handler(e))}?: (...args: any[]) => any`)
  lines.push('}')
  lines.push(`export declare const ${name}: DefineComponent<${name}Props>`, '')
}

lines.push(`// ── Composables ──────────────────────────────────────────────────────────
export interface InfiniteListOptions {
  pageSize?: number
  /** Getters whose change resets the list to its first page */
  resetOn?: Array<() => unknown>
  /** Scroll container (selector or element); default 'main' */
  scroller?: string | Element | null
  firstDelay?: number
  nextDelay?: number
  rootMargin?: number
}
export declare function useInfiniteList<T>(list: Ref<T[]> | ComputedRef<T[]>, options?: InfiniteListOptions): {
  shown: ComputedRef<T[]>
  hasMore: ComputedRef<boolean>
  loading: Ref<boolean>
  loadingMore: Ref<boolean>
  sentinel: Ref<HTMLElement | null>
  [key: string]: any
}
export declare function useStuck(options?: { scroller?: string | Element | null }): {
  sentinel: Ref<HTMLElement | null>
  stuck: Ref<boolean>
  update: () => void
}
export declare function useFloating(anchor: Ref<any>, options?: {
  align?: 'start' | 'end' | 'stretch'
  gap?: number
  width?: number | null
  minBelow?: number
}): {
  style: Ref<Record<string, string>>
  placement: Ref<'top' | 'bottom'>
  maxHeight: Ref<number>
  update: () => void
  start: () => void
  stop: () => void
}

// ── Toast ────────────────────────────────────────────────────────────────
export type ToastTone = 'success' | 'reward' | 'danger'
export interface Toast { id: number; message: string; tone: ToastTone }
export declare const toasts: Toast[]
/** Show a toast; render <AppToaster /> once in the app. Returns its id. */
export declare function toast(message: string, tone?: ToastTone, ms?: number): number
`)

writeFileSync('src/index.d.ts', lines.join('\n'))
console.log(`✓ src/index.d.ts — ${comps.length} components`)
